export const actionLabel = (permission: string, resourcePrefix: string) =>
  permission
    .replace(`${resourcePrefix}_`, "")
    .replace(/_/g, " ")
    .toLowerCase()
    .replace(/^\w/, (c) => c.toUpperCase())

